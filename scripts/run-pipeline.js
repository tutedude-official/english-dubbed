require("dotenv").config();

// Parse --voice=male|female (default: male → shubh, female → roopa)
const _voiceArg = process.argv.find(a => a.startsWith("--voice="));
const _voiceGender = _voiceArg ? _voiceArg.split("=")[1].toLowerCase() : "male";
process.env.SARVAM_SPEAKER = _voiceGender === "female" ? "roopa" : "shubh";

const fs = require("fs");
const path = require("path");
const https = require("https");
const { processPipeline } = require("../src/pipeline");
const { uploadToS3, existsOnS3 } = require("../src/services/s3");
const { S3_BUCKET, S3_PREFIX } = require("../src/config");
const { fmtDuration, fmtMs } = require("../src/utils/format");
const L = require("../src/utils/logger");

// ── Constants ─────────────────────────────────────────────────────────────────

const CLOUDFRONT_BASE = "https://d44tj0kek3n57.cloudfront.net/transcoded";
const OUTPUT_DIR      = path.join(__dirname, "../output");
const COURSE_JSON     = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.join(__dirname, "../data/course.json");
const courseSlug       = path.basename(COURSE_JSON, ".json");
const MISSING_VTT_FILE = path.join(__dirname, `../missing_vtt_${courseSlug}.json`);
const COMPLETED_FILE  = path.join(__dirname, `../completed_${courseSlug}.json`);

// ── Helpers ───────────────────────────────────────────────────────────────────

function fetchVTT(url) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, (res) => {
      if (res.statusCode === 404 || res.statusCode === 403) { res.resume(); return resolve(null); }
      if (res.statusCode !== 200) { res.resume(); return reject(new Error(`HTTP ${res.statusCode} fetching VTT`)); }
      const chunks = [];
      res.on("data", (c) => chunks.push(c));
      res.on("end", () => resolve(Buffer.concat(chunks).toString("utf-8")));
    });
    req.on("error", reject);
    req.setTimeout(30000, () => { req.destroy(); reject(new Error("VTT fetch timeout")); });
  });
}

function loadCompleted(filePath) {
  const f = filePath || COMPLETED_FILE;
  if (fs.existsSync(f)) {
    return new Set(JSON.parse(fs.readFileSync(f, "utf-8")));
  }
  return new Set();
}

function saveCompleted(set, filePath) {
  const f = filePath || COMPLETED_FILE;
  fs.writeFileSync(f, JSON.stringify([...set], null, 2), "utf-8");
}

// ── Process one lecture ───────────────────────────────────────────────────────

async function processLecture(lecture, index, total) {
  const lectureStart = Date.now();
  const lectureId  = lecture._id.$oid;
  const tpStreamId = lecture.tpStreamId;
  const vttUrl     = `${CLOUDFRONT_BASE}/${tpStreamId}/subtitles/en-autogenerated.vtt`;

  L.banner(`Lecture [${index}/${total}]: ${lecture.lectureName}`);
  L.kv("Section:", lecture.sectionName);
  L.kv("ID:", lectureId);
  L.kv("tpStream:", tpStreamId);
  L.kv("VTT URL:", vttUrl);
  L.divider();

  // Step 0 — Skip if already present on S3
  const audioKeyCheck = `${S3_PREFIX}/${lectureId}/audio.wav`;
  const vttKeyCheck   = `${S3_PREFIX}/${lectureId}/audio.vtt`;
  L.write("  Step 0/3  Checking S3 for existing output... ");
  try {
    const [hasAudio, hasVtt] = await Promise.all([
      existsOnS3(audioKeyCheck),
      existsOnS3(vttKeyCheck),
    ]);
    L.detail(`hasAudio (${audioKeyCheck}): ${hasAudio}`);
    L.detail(`hasVtt   (${vttKeyCheck}): ${hasVtt}`);
    if (hasAudio && hasVtt) {
      L.done("ALREADY PRESENT");
      L.success(`Skipping — s3://${S3_BUCKET}/${S3_PREFIX}/${lectureId}/ already has audio.wav + audio.vtt`);
      return {
        status: "skipped",
        lectureId,
        lectureName: lecture.lectureName,
        tpStreamId,
        sectionName: lecture.sectionName,
        s3Audio: `s3://${S3_BUCKET}/${audioKeyCheck}`,
        s3Vtt: `s3://${S3_BUCKET}/${vttKeyCheck}`,
      };
    }
    L.done(hasAudio || hasVtt ? "PARTIAL — will regenerate" : "NOT FOUND");
  } catch (err) {
    L.append("CHECK FAILED");
    L.warn(`S3 existence check error (will process anyway): ${err.message}`);
  }

  // Step 1 — Fetch VTT
  const fetchStart = Date.now();
  L.write("  Step 1/3  Fetching Hinglish VTT... ");

  let vttContent;
  try {
    vttContent = await fetchVTT(vttUrl);
  } catch (err) {
    L.append(`FAILED (${fmtMs(Date.now() - fetchStart)})`);
    L.error(`Fetch error: ${err.message}`);
    return { status: "error", lectureId, lectureName: lecture.lectureName, tpStreamId, error: err.message };
  }

  if (!vttContent || !vttContent.includes("WEBVTT")) {
    L.append(`NOT FOUND (${fmtMs(Date.now() - fetchStart)})`);
    L.error("No subtitles available for this lecture");
    return { status: "missing", lectureId, lectureName: lecture.lectureName, tpStreamId, vttUrl };
  }

  const vttLines = vttContent.split("\n").length;
  L.done(`(${fmtMs(Date.now() - fetchStart)})  [${vttLines} lines]`);

  // Setup paths
  const lectureDir  = path.join(OUTPUT_DIR, lectureId);
  const tmpDir      = path.join(lectureDir, "tmp");
  fs.mkdirSync(lectureDir, { recursive: true });
  fs.mkdirSync(tmpDir, { recursive: true });

  const inputVTT    = path.join(lectureDir, "input.vtt");
  const outputVTT   = path.join(lectureDir, "english.vtt");
  const outputAudio = path.join(lectureDir, "english.wav");

  fs.writeFileSync(inputVTT, vttContent, "utf-8");
  L.success(`VTT saved locally → ${inputVTT}`);

  // Step 2 — Convert
  const convertStart = Date.now();
  L.step("\n  Step 2/3  Running English conversion pipeline...");

  let pipelineResult;
  try {
    pipelineResult = await processPipeline(inputVTT, outputVTT, outputAudio, tmpDir);
  } catch (err) {
    L.error(`Pipeline failed after ${fmtDuration(Date.now() - convertStart)}: ${err.message}`);
    throw err;
  }

  const convertMs = Date.now() - convertStart;
  L.success(`Conversion done in ${fmtDuration(convertMs)}  accuracy=${pipelineResult.accuracy}%`);

  // Step 3 — Upload
  const uploadStart = Date.now();
  const audioKey    = `${S3_PREFIX}/${lectureId}/audio.wav`;
  const vttKey      = `${S3_PREFIX}/${lectureId}/audio.vtt`;

  L.step("\n  Step 3/3  Uploading to S3...");

  const audioSizeMB = (fs.statSync(outputAudio).size / 1024 / 1024).toFixed(1);
  const vttSizeKB   = (fs.statSync(outputVTT).size / 1024).toFixed(1);

  L.write(`    Uploading audio.wav... `);
  await uploadToS3(outputAudio, audioKey);
  L.done(`[${audioSizeMB} MB]`);

  L.write(`    Uploading audio.vtt...  `);
  await uploadToS3(outputVTT, vttKey);
  L.done(`[${vttSizeKB} KB]`);

  const uploadMs = Date.now() - uploadStart;
  const totalMs  = Date.now() - lectureStart;

  L.success(`Upload done in ${fmtDuration(uploadMs)}`);

  // Cleanup tmp
  if (fs.existsSync(tmpDir)) {
    fs.rmSync(tmpDir, { recursive: true, force: true });
    L.success(`Deleted tmp folder → ${tmpDir}`);
  }

  L.divider();
  L.success(`LECTURE DONE — total time: ${fmtDuration(totalMs)}`);
  L.detail(`Convert: ${fmtDuration(convertMs)}  |  Upload: ${fmtDuration(uploadMs)}`);

  return {
    status: "success",
    lectureId,
    lectureName: lecture.lectureName,
    tpStreamId,
    sectionName: lecture.sectionName,
    localDir: lectureDir,
    s3Audio: `s3://${S3_BUCKET}/${audioKey}`,
    s3Vtt: `s3://${S3_BUCKET}/${vttKey}`,
    timing: { convertMs, uploadMs, totalMs },
    accuracy: pipelineResult.accuracy,
    audioDuration: pipelineResult.totalDuration,
  };
}

// ── Main ──────────────────────────────────────────────────────────────────────

async function main(courseJsonOverride, options = {}) {
  const { lectureLimit = null } = options;
  const courseJsonPath = courseJsonOverride || COURSE_JSON;
  const slug = path.basename(courseJsonPath, ".json");
  const completedFile = courseJsonOverride
    ? path.join(__dirname, `../completed_${slug}.json`)
    : COMPLETED_FILE;
  const missingVttFile = courseJsonOverride
    ? path.join(__dirname, `../missing_vtt_${slug}.json`)
    : MISSING_VTT_FILE;
  if (!process.env.OPENAI_API_KEY) { L.error("OPENAI_API_KEY missing in .env"); process.exit(1); }
  if (!process.env.AWS_ACCESS_KEY_ID || process.env.AWS_ACCESS_KEY_ID === "your_aws_access_key_here") {
    L.error("AWS_ACCESS_KEY_ID missing or not set in .env"); process.exit(1);
  }
  if (!process.env.AWS_SECRET_ACCESS_KEY || process.env.AWS_SECRET_ACCESS_KEY === "your_aws_secret_key_here") {
    L.error("AWS_SECRET_ACCESS_KEY missing or not set in .env"); process.exit(1);
  }

  const runStart   = Date.now();
  const courseData = JSON.parse(fs.readFileSync(courseJsonPath, "utf-8"));
  const allLectures = [];
  for (const section of courseData.sections) {
    for (const lecture of section.lectures) {
      allLectures.push({ ...lecture, sectionName: section.sectionName });
    }
  }

  const completed = loadCompleted(completedFile);
  let pending   = allLectures.filter((l) => !completed.has(l._id.$oid));
  
  // Apply lecture limit if specified
  const originalPendingCount = pending.length;
  if (lectureLimit && lectureLimit > 0 && pending.length > lectureLimit) {
    pending = pending.slice(0, lectureLimit);
  }

  L.banner(`ENGLISH DUB PIPELINE — ${courseData.courseName}`);
  L.kv("Course:", courseData.courseName);
  L.kv("Course file:", courseJsonPath);
  L.kv("Total lectures:", String(allLectures.length));
  L.kv("Already done:", String(completed.size));
  L.kv("Pending (total):", String(originalPendingCount));
  if (lectureLimit && lectureLimit > 0) {
    L.kv("Lecture limit:", String(lectureLimit));
  }
  L.kv("Voice:", `${_voiceGender} (${process.env.SARVAM_SPEAKER})`);
  L.kv("To process now:", String(pending.length));
  L.kv("Output dir:", OUTPUT_DIR);
  L.kv("S3 destination:", `s3://${S3_BUCKET}/${S3_PREFIX}/{lectureId}/`);
  L.divider();

  if (pending.length === 0) {
    L.warn("All lectures already processed. Nothing to do.");
    console.log();
    return;
  }

  fs.mkdirSync(OUTPUT_DIR, { recursive: true });

  const results     = { success: [], skipped: [], missing: [], errors: [] };
  const lectureTimes = [];

  for (let i = 0; i < pending.length; i++) {
    const lecture = pending[i];

    if (lectureTimes.length > 0) {
      const avgMs    = lectureTimes.reduce((a, b) => a + b, 0) / lectureTimes.length;
      const remaining = pending.length - i;
      L.info(`─── Progress: ${i}/${pending.length} done  |  ETA ~${fmtDuration(avgMs * remaining)}  |  avg ${fmtDuration(avgMs)}/lecture ───`);
    }

    try {
      const result = await processLecture(lecture, i + 1, pending.length);

      if (result.status === "success") {
        results.success.push(result);
        lectureTimes.push(result.timing.totalMs);
        completed.add(result.lectureId);
        saveCompleted(completed, completedFile);
      } else if (result.status === "skipped") {
        results.skipped.push(result);
        completed.add(result.lectureId);
        saveCompleted(completed, completedFile);
      } else if (result.status === "missing") {
        results.missing.push(result);
      } else {
        results.errors.push(result);
      }
    } catch (err) {
      L.error(`Fatal error for "${lecture.lectureName}": ${err.message}`);
      results.errors.push({
        status: "error",
        lectureId: lecture._id.$oid,
        lectureName: lecture.lectureName,
        tpStreamId: lecture.tpStreamId,
        sectionName: lecture.sectionName,
        error: err.message,
      });
    }

    const missingOrError = [...results.missing, ...results.errors];
    if (missingOrError.length > 0) {
      fs.writeFileSync(missingVttFile, JSON.stringify(missingOrError, null, 2), "utf-8");
    }
  }

  // Final summary
  const totalRunMs    = Date.now() - runStart;
  const avgLectureMs  = lectureTimes.length
    ? lectureTimes.reduce((a, b) => a + b, 0) / lectureTimes.length
    : 0;

  L.banner(`ENGLISH DUB PIPELINE — ${courseData.courseName} — COMPLETE`);
  L.kv("✓ Succeeded:", String(results.success.length));
  L.kv("↷ Skipped (on S3):", String(results.skipped.length));
  L.kv("✗ Missing VTT:", String(results.missing.length));
  L.kv("✗ Errors:", String(results.errors.length));
  L.thinDivider();
  L.kv("Total wall time:", fmtDuration(totalRunMs));
  if (avgLectureMs > 0) L.kv("Avg per lecture:", fmtDuration(avgLectureMs));

  if (results.success.length > 0) {
    L.step("\n  Successful lectures:");
    for (const r of results.success) {
      L.success(`[${r.sectionName}] ${r.lectureName}  (${fmtDuration(r.timing.totalMs)})  accuracy=${r.accuracy}%`);
    }
  }
  if (results.missing.length > 0) {
    L.step("\n  Missing VTT (saved to missing_vtt.json):");
    for (const m of results.missing) {
      L.warn(`[${m.sectionName || "?"}] ${m.lectureName}  tpStream=${m.tpStreamId}`);
    }
  }
  if (results.errors.length > 0) {
    L.step("\n  Errors:");
    for (const e of results.errors) {
      L.error(`${e.lectureName}: ${e.error}`);
    }
  }

  L.divider();
  console.log();
}

module.exports = { main };

if (require.main === module) {
  main().catch((err) => {
    L.error(`Fatal: ${err.message}`);
    process.exit(1);
  });
}
