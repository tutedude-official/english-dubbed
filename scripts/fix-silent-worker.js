// Worker: for one course JSON, downloads each lecture's audio.wav from S3,
// checks silence, and regenerates + re-uploads silent ones using current SARVAM_VOICE.
//
// SARVAM_VOICE env must be set BEFORE this file requires ../src/config (which happens
// transitively via ../src/pipeline). The orchestrator (fix-silent.js) is responsible
// for spawning this worker with the correct SARVAM_VOICE env var.

require("dotenv").config();

const fs = require("fs");
const path = require("path");
const https = require("https");
const { S3Client, GetObjectCommand } = require("@aws-sdk/client-s3");

const { processPipeline } = require("../src/pipeline");
const { uploadToS3 } = require("../src/services/s3");
const { notifyLmsDubReady } = require("../src/services/notifyLms");
const { isSilentAudio } = require("../src/services/audio");
const {
  S3_BUCKET,
  S3_PREFIX,
  AWS_ACCESS_KEY_ID,
  AWS_SECRET_ACCESS_KEY,
  AWS_REGION,
  SARVAM_SPEAKER,
} = require("../src/config");
const { fmtDuration, fmtMs } = require("../src/utils/format");
const L = require("../src/utils/logger");

const CLOUDFRONT_BASE = "https://d44tj0kek3n57.cloudfront.net/transcoded";
const OUTPUT_DIR = path.join(__dirname, "../output");

const COURSE_JSON = process.argv[2] ? path.resolve(process.argv[2]) : null;
if (!COURSE_JSON) {
  console.error("Usage: node scripts/fix-silent-worker.js <course.json>");
  process.exit(1);
}

const s3 = new S3Client({
  region: AWS_REGION,
  credentials: {
    accessKeyId: AWS_ACCESS_KEY_ID,
    secretAccessKey: AWS_SECRET_ACCESS_KEY,
  },
});

async function downloadFromS3(s3Key, localPath) {
  const response = await s3.send(new GetObjectCommand({ Bucket: S3_BUCKET, Key: s3Key }));
  const chunks = [];
  for await (const chunk of response.Body) chunks.push(chunk);
  fs.writeFileSync(localPath, Buffer.concat(chunks));
}

function fetchVTT(url) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, (res) => {
      if (res.statusCode === 404 || res.statusCode === 403) { res.resume(); return resolve(null); }
      if (res.statusCode !== 200) { res.resume(); return reject(new Error(`HTTP ${res.statusCode}`)); }
      const chunks = [];
      res.on("data", (c) => chunks.push(c));
      res.on("end", () => resolve(Buffer.concat(chunks).toString("utf-8")));
    });
    req.on("error", reject);
    req.setTimeout(30000, () => { req.destroy(); reject(new Error("Timeout")); });
  });
}

async function regenerateAndUpload(lecture) {
  const lectureId = lecture._id.$oid;
  const tpStreamId = lecture.tpStreamId;
  if (!tpStreamId) {
    L.error(`    ✗ no tpStreamId on lecture record — cannot fetch VTT`);
    return { status: "error", lectureId, error: "no tpStreamId" };
  }

  const vttUrl = `${CLOUDFRONT_BASE}/${tpStreamId}/subtitles/en-autogenerated.vtt`;
  const lectureDir = path.join(OUTPUT_DIR, lectureId);
  const tmpDir = path.join(lectureDir, "tmp");
  fs.mkdirSync(lectureDir, { recursive: true });
  fs.mkdirSync(tmpDir, { recursive: true });

  const inputVTT = path.join(lectureDir, "input.vtt");
  const outputVTT = path.join(lectureDir, "english.vtt");
  const outputAudio = path.join(lectureDir, "english.wav");

  try {
    L.step(`    ▸ Step 1/3  Fetching VTT for tpStream=${tpStreamId}`);
    L.detail(`URL: ${vttUrl}`);
    const vttContent = await fetchVTT(vttUrl);
    if (!vttContent || !vttContent.includes("WEBVTT")) {
      L.warn(`    ⚠ VTT missing/invalid at source — skipping regen for ${lectureId}`);
      return { status: "missing_vtt", lectureId };
    }
    fs.writeFileSync(inputVTT, vttContent, "utf-8");
    L.success(`    ✓ VTT fetched (${vttContent.split("\n").length} lines)`);

    L.step(`    ▸ Step 2/3  Running TTS pipeline (voice=${process.env.SARVAM_VOICE || "male"}, speaker=${SARVAM_SPEAKER})`);
    const t0 = Date.now();
    const pipelineResult = await processPipeline(inputVTT, outputVTT, outputAudio, tmpDir);
    L.success(`    ✓ Pipeline done in ${fmtDuration(Date.now() - t0)}  accuracy=${pipelineResult.accuracy}%`);

    const audioKey = `${S3_PREFIX}/${lectureId}/audio.wav`;
    const vttKey = `${S3_PREFIX}/${lectureId}/audio.vtt`;
    const audioSizeMB = (fs.statSync(outputAudio).size / 1024 / 1024).toFixed(2);
    const vttSizeKB = (fs.statSync(outputVTT).size / 1024).toFixed(1);

    L.step(`    ▸ Step 3/3  Uploading to S3 (overwriting silent version)`);
    L.write(`      → s3://${S3_BUCKET}/${audioKey} [${audioSizeMB} MB] `);
    await uploadToS3(outputAudio, audioKey);
    L.done("uploaded");
    L.write(`      → s3://${S3_BUCKET}/${vttKey} [${vttSizeKB} KB] `);
    await uploadToS3(outputVTT, vttKey);
    L.done("uploaded");

    // Notify the LMS backend that this dub is live.
    const notified = await notifyLmsDubReady({ lectureId, s3Key: audioKey, subtitleS3Key: vttKey });
    if (notified.ok) L.success("    ✓ Notified LMS backend");

    return { status: "success", lectureId, accuracy: pipelineResult.accuracy };
  } catch (err) {
    L.error(`    ✗ Regen error: ${err.message}`);
    return { status: "error", lectureId, error: err.message };
  } finally {
    if (fs.existsSync(lectureDir)) fs.rmSync(lectureDir, { recursive: true, force: true });
  }
}

async function main() {
  if (!process.env.OPENAI_API_KEY) { L.error("OPENAI_API_KEY missing"); process.exit(1); }
  if (!AWS_ACCESS_KEY_ID) { L.error("AWS_ACCESS_KEY_ID missing"); process.exit(1); }

  const courseData = JSON.parse(fs.readFileSync(COURSE_JSON, "utf-8"));
  const allLectures = [];
  for (const section of courseData.sections) {
    for (const lecture of section.lectures) {
      allLectures.push({ ...lecture, sectionName: section.sectionName });
    }
  }

  const courseSlug = path.basename(COURSE_JSON, ".json");
  const tmpCheckDir = path.join(__dirname, `../tmp_silent_check_${courseSlug}`);
  fs.mkdirSync(tmpCheckDir, { recursive: true });
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });

  L.banner(`FIX SILENT — ${courseData.courseName}`);
  L.kv("Course file:", COURSE_JSON);
  L.kv("Total lectures:", String(allLectures.length));
  L.kv("Voice:", `${process.env.SARVAM_VOICE || "male"} (speaker=${SARVAM_SPEAKER})`);
  L.kv("S3:", `s3://${S3_BUCKET}/${S3_PREFIX}/{lectureId}/audio.wav`);
  L.divider();

  const stats = { checked: 0, silent: 0, notFound: 0, checkErr: 0, regenSuccess: 0, regenErr: 0, missingVtt: 0 };
  const silentIds = [];
  const regenErrors = [];

  for (let i = 0; i < allLectures.length; i++) {
    const lecture = allLectures[i];
    const lectureId = lecture._id.$oid;
    const s3Key = `${S3_PREFIX}/${lectureId}/audio.wav`;
    const localFile = path.join(tmpCheckDir, `${lectureId}.wav`);

    L.info(`[${i + 1}/${allLectures.length}] ${lecture.lectureName}`);
    L.detail(`lectureId=${lectureId}  section="${lecture.sectionName}"  tpStream=${lecture.tpStreamId || "(none)"}`);
    L.detail(`s3://${S3_BUCKET}/${s3Key}`);

    let silent = false;
    let sizeKB = null;
    try {
      const dlStart = Date.now();
      await downloadFromS3(s3Key, localFile);
      sizeKB = (fs.statSync(localFile).size / 1024).toFixed(1);
      silent = isSilentAudio(localFile);
      stats.checked++;
      if (silent) {
        stats.silent++;
        silentIds.push(lectureId);
        L.warn(`  ✗ SILENT  (size=${sizeKB} KB, dl=${fmtMs(Date.now() - dlStart)})  → will regenerate`);
      } else {
        L.success(`  ✓ NOT SILENT — has audio (size=${sizeKB} KB, dl=${fmtMs(Date.now() - dlStart)})`);
      }
    } catch (err) {
      if (err.name === "NoSuchKey" || err.$metadata?.httpStatusCode === 404) {
        stats.notFound++;
        L.warn(`  ⏭  NOT FOUND on S3 — no audio file exists for this lecture`);
      } else {
        stats.checkErr++;
        L.error(`  ✗ CHECK ERROR: ${err.message}`);
      }
    } finally {
      if (fs.existsSync(localFile)) fs.unlinkSync(localFile);
    }

    if (silent) {
      L.step(`  ► REGENERATING silent lecture ${lectureId}`);
      const start = Date.now();
      const r = await regenerateAndUpload(lecture);
      const took = fmtDuration(Date.now() - start);
      if (r.status === "success") {
        stats.regenSuccess++;
        L.success(`  ★ REGEN DONE  lectureId=${lectureId}  time=${took}  accuracy=${r.accuracy}%`);
      } else if (r.status === "missing_vtt") {
        stats.missingVtt++;
        regenErrors.push({ lectureId, lectureName: lecture.lectureName, error: "missing_vtt" });
        L.warn(`  ★ REGEN SKIPPED  lectureId=${lectureId}  reason=MISSING VTT`);
      } else {
        stats.regenErr++;
        regenErrors.push({ lectureId, lectureName: lecture.lectureName, error: r.error });
        L.error(`  ★ REGEN FAILED  lectureId=${lectureId}  time=${took}  error=${r.error}`);
      }
    }

    L.thinDivider();
  }

  if (fs.existsSync(tmpCheckDir)) fs.rmSync(tmpCheckDir, { recursive: true, force: true });

  L.banner(`FIX SILENT DONE — ${courseData.courseName}`);
  L.kv("Checked (audio present):", String(stats.checked));
  L.kv("Silent found:", String(stats.silent));
  L.kv("Regenerated OK:", String(stats.regenSuccess));
  L.kv("Missing VTT:", String(stats.missingVtt));
  L.kv("Regen errors:", String(stats.regenErr));
  L.kv("S3 not found:", String(stats.notFound));
  L.kv("Check errors:", String(stats.checkErr));
  L.divider();

  if (silentIds.length > 0) {
    L.step("\n  Silent lecture IDs (regenerated or attempted):");
    silentIds.forEach((id) => console.log(`    - ${id}`));
  }
  if (regenErrors.length > 0) {
    L.step("\n  Regen errors:");
    regenErrors.forEach((e) => console.log(`    - ${e.lectureId}  ${e.lectureName}  :: ${e.error}`));
  }

  const report = {
    course: courseData.courseName,
    slug: courseSlug,
    finishedAt: new Date().toISOString(),
    voice: process.env.SARVAM_VOICE || "male",
    speaker: SARVAM_SPEAKER,
    stats,
    silentLectureIds: silentIds,
    regenErrors,
  };
  const reportPath = path.join(__dirname, `../fix_silent_report_${courseSlug}.json`);
  fs.writeFileSync(reportPath, JSON.stringify(report, null, 2), "utf-8");
  L.success(`Report → ${reportPath}`);
}

main().catch((err) => {
  L.error(`Fatal: ${err.message}`);
  process.exit(1);
});
